#!/usr/bin/env python3
"""Deterministic multi-sample integration benchmark; Python standard library only."""
from __future__ import annotations

import argparse
from collections import Counter
import csv
import gzip
import hashlib
import json
from pathlib import Path
import platform
import random
import shlex
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[2]
FIELDS = ["sample", "total_reads", "extracted_reads", "unique_reads",
          "ambiguous_reads", "unassigned_reads", "extraction_failed_reads"]
ANCHOR1, ANCHOR2 = "ACGTAC", "TGCATG"


def table(path, header, rows):
    with path.open("w", newline="") as handle:
        writer = csv.writer(handle, delimiter="\t", lineterminator="\n")
        writer.writerow(header)
        writer.writerows(rows)


def read_table(path):
    with path.open(newline="") as handle:
        return list(csv.reader(handle, delimiter="\t"))


def sha(path):
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def rc(seq):
    return seq.translate(str.maketrans("ACGT", "TGCA"))[::-1]


def verify(out, results):
    checks = {}
    for name in ("count_table.count.txt", "assignment_summary.tsv", "library_recovery.tsv"):
        expected = read_table(out / "truth" / name)
        observed = read_table(results / name)
        if observed != expected:
            raise ValueError(f"Truth mismatch: {results / name}")
        checks[name] = "PASS"
    summary = read_table(results / "assignment_summary.tsv")
    for row in summary[1:]:
        metrics = dict(zip(summary[0], row))
        total = int(metrics["total_reads"])
        unique = int(metrics["unique_reads"])
        ambiguous = int(metrics["ambiguous_reads"])
        unassigned = int(metrics["unassigned_reads"])
        failed = int(metrics["extraction_failed_reads"])
        if unique + ambiguous + unassigned + failed != total:
            raise ValueError(f"Read conservation failed: {row[0]}")
        if int(metrics["extracted_reads"]) != unique + ambiguous + unassigned:
            raise ValueError(f"Extracted read conservation failed: {row[0]}")
    checks["read_pair_conservation"] = "PASS"
    return checks


def generate(args, out):
    rng = random.Random(args.seed)
    n = args.constructs
    # Two duplicate rows share one signature; the last 10% are unique but unobserved.
    zero_count = max(1, n // 10)
    observed_n = n - zero_count - 2
    signatures, used = [], set()
    while len(signatures) < n - 1:
        pair = tuple("".join(rng.choices("ACGT", k=20)) for _ in range(2))
        if pair not in used:
            signatures.append(pair)
            used.add(pair)
    duplicate = signatures[observed_n]
    pairs = signatures[:observed_n] + [duplicate, duplicate] + signatures[observed_n + 1:]
    unknown = ("A" * 20, "C" * 20)
    if unknown in used:
        raise ValueError("Seed unexpectedly produced the reserved unknown signature")
    ids = [f"construct_{i:06d}" for i in range(n)]
    targets = [f"TARGET_{i // 4:06d}" for i in range(n)]
    table(out / "inputs/library.tsv", ["construct_id", "target_id", "spacer_r1", "spacer_r2"],
          ([ids[i], targets[i], *pairs[i]] for i in range(n)))
    counts, summaries, samplesheet = {}, [], []
    for sample_index in range(args.samples):
        sample = f"{'control' if sample_index < args.samples // 2 else 'treatment'}_{sample_index + 1:02d}"
        condition = sample.split("_")[0]
        sample_counts, metrics = Counter(), Counter()
        paths = [out / "inputs" / f"{sample}_R{end}.fastq.gz" for end in (1, 2)]
        # Gzip mtime and filename are fixed so regenerated bytes are reproducible.
        with paths[0].open("wb") as raw1, paths[1].open("wb") as raw2:
            with gzip.GzipFile(filename="", fileobj=raw1, mode="wb", mtime=0, compresslevel=1) as f1, \
                 gzip.GzipFile(filename="", fileobj=raw2, mode="wb", mtime=0, compresslevel=1) as f2:
                for j in range(args.pairs_per_sample):
                    category = j % 100
                    if category < 85:
                        index = rng.randrange(observed_n)
                        guide1, guide2 = pairs[index]
                        sample_counts[ids[index]] += 1
                        metrics["unique_reads"] += 1
                    elif category < 90:
                        guide1, guide2 = duplicate
                        metrics["ambiguous_reads"] += 1
                    elif category < 95:
                        guide1, guide2 = unknown
                        metrics["unassigned_reads"] += 1
                    else:
                        guide1, guide2 = pairs[0]
                        metrics["extraction_failed_reads"] += 1
                    seq1 = ANCHOR1 + "GG" + guide1 + "T" * 122
                    seq2 = ANCHOR2 + "GG" + guide2 + "T" * 122
                    if category >= 95:
                        # Missing anchor or short window, alternating read end.
                        if j % 2:
                            seq1 = "T" * 150
                        else:
                            seq2 = ANCHOR2 + "GG" + guide2[:5]
                    seq2 = rc(seq2)
                    for end, seq, handle in ((1, seq1, f1), (2, seq2, f2)):
                        handle.write(f"@{sample}_{j}/{end}\n{seq}\n+\n{'I' * len(seq)}\n".encode())
        counts[sample] = sample_counts
        summaries.append([sample, args.pairs_per_sample,
                          args.pairs_per_sample - metrics["extraction_failed_reads"],
                          *[metrics[k] for k in FIELDS[3:]]])
        samplesheet.append([sample, *map(str, paths), condition])
        print(f"Generated {sample}: {args.pairs_per_sample:,} pairs", flush=True)
    with (out / "inputs/samplesheet.csv").open("w", newline="") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["sample", "fastq_1", "fastq_2", "condition"])
        writer.writerows(samplesheet)
    samples = sorted(counts)
    table(out / "truth/count_table.count.txt", ["sgRNA", "Gene", *samples],
          ([ids[i], targets[i], *[counts[s][ids[i]] for s in samples]] for i in range(n)))
    table(out / "truth/assignment_summary.tsv", FIELDS, sorted(summaries))
    table(out / "truth/library_recovery.tsv",
          ["construct_id", "target_id", "assignability_class", "duplicate_signature_size", "total_count", "zero_count"],
          ([ids[i], targets[i], "ambiguous" if i in (observed_n, observed_n + 1) else "unique",
            2 if i in (observed_n, observed_n + 1) else 1,
            sum(counts[s][ids[i]] for s in samples),
            str(sum(counts[s][ids[i]] for s in samples) == 0).lower()] for i in range(n)))
    params = {
        "analysis": "screening", "screening_count_method": "crisprdecode",
        "input": str(out / "inputs/samplesheet.csv"), "library": str(out / "inputs/library.tsv"),
        "outdir": str(out / "nextflow_results"), "crisprdecode_r1_anchor": ANCHOR1,
        "crisprdecode_r2_anchor": ANCHOR2, "crisprdecode_r1_offset": 2,
        "crisprdecode_r2_offset": 2, "crisprdecode_reverse_complement_r2": True,
    }
    (out / "inputs/params.json").write_text(json.dumps(params, indent=2) + "\n")
    return samplesheet


def run(args, out):
    started = time.perf_counter()
    out.mkdir(parents=True, exist_ok=False)
    for directory in ("inputs", "truth", "results", "logs"):
        (out / directory).mkdir()
    report = {
        "status": "RUNNING", "scope": "Python validate -> assign -> aggregate; synthetic data",
        "seed": args.seed, "constructs": args.constructs, "samples": args.samples,
        "pairs_per_sample": args.pairs_per_sample, "python": sys.version,
        "platform": platform.platform(), "commands": [], "timings_seconds": {},
        "invocation": shlex.join([sys.executable, *sys.argv]),
        "git_commit": subprocess.check_output(["git", "-C", str(ROOT), "rev-parse", "HEAD"], text=True).strip(),
        "source_sha256": {str(p.relative_to(ROOT)): sha(p) for p in
                          [Path(__file__).resolve(), *sorted((ROOT / "bin").glob("crisprdecode_*.py"))]},
    }
    def save():
        (out / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    def execute(name, script, *arguments):
        cmd = [sys.executable, str(ROOT / "bin" / script), *map(str, arguments)]
        report["commands"].append(shlex.join(cmd))
        begin = time.perf_counter()
        with (out / "logs" / f"{name}.log").open("w") as log:
            result = subprocess.run(cmd, stdout=log, stderr=subprocess.STDOUT)
        report["timings_seconds"][name] = round(time.perf_counter() - begin, 4)
        save()
        if result.returncode:
            raise RuntimeError(f"{name} failed ({result.returncode}); see logs/{name}.log")
    try:
        samplesheet = generate(args, out)
        report["timings_seconds"]["generate"] = round(time.perf_counter() - started, 4)
        report["input_sha256"] = {p.name: sha(p) for p in sorted((out / "inputs").iterdir())}
        save()
        result = out / "results"
        validated = result / "validated_construct_library.tsv"
        execute("validate", "crisprdecode_validate_library.py",
                "--library", out / "inputs/library.tsv", "--output", validated)
        count_files, summary_files = [], []
        for sample, r1, r2, _condition in samplesheet:
            count = result / f"{sample}.counts.tsv"
            summary = result / f"{sample}.summary.tsv"
            execute(sample, "crisprdecode_assign.py", "--library", validated, "--sample", sample,
                    "--r1", r1, "--r2", r2, "--r1-anchor", ANCHOR1, "--r2-anchor", ANCHOR2,
                    "--r1-offset", 2, "--r2-offset", 2, "--reverse-complement-r2",
                    "--counts", count, "--summary", summary)
            count_files.append(count)
            summary_files.append(summary)
        execute("aggregate", "crisprdecode_aggregate.py", "--library", validated,
                "--sample-counts", *count_files, "--sample-summaries", *summary_files,
                "--count-matrix", result / "count_table.count.txt",
                "--assignment-summary", result / "assignment_summary.tsv",
                "--library-recovery", result / "library_recovery.tsv")
        report["checks"] = verify(out, result)
        report["status"] = "PASS"
    except Exception as error:
        report["status"], report["error"] = "FAIL", str(error)
        raise
    finally:
        report["timings_seconds"]["total"] = round(time.perf_counter() - started, 4)
        save()
    print(json.dumps({"status": report["status"], "checks": report["checks"],
                      "timings_seconds": report["timings_seconds"]}, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--outdir", type=Path, required=True, help="New output directory; never overwrites")
    parser.add_argument("--constructs", type=int, default=10000)
    parser.add_argument("--samples", type=int, default=6)
    parser.add_argument("--pairs-per-sample", type=int, default=1000000)
    parser.add_argument("--seed", type=int, default=20261007)
    parser.add_argument("--verify-results", type=Path, help="Check existing Nextflow crisprdecode/ outputs against truth")
    args = parser.parse_args()
    if args.verify_results:
        print(json.dumps(verify(args.outdir.resolve(), args.verify_results.resolve()), indent=2))
        return
    if args.constructs < 10 or args.samples < 2 or args.pairs_per_sample < 100:
        parser.error("Require constructs >= 10, samples >= 2 and pairs-per-sample >= 100")
    run(args, args.outdir.resolve())


if __name__ == "__main__":
    main()
